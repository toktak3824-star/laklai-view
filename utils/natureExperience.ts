// =========================================
// ตรวจว่าวันที่นี้เป็นวันที่งดกิจกรรมหรือไม่
// =========================================

function isNatureExperienceClosedDate(
  activityDate: string
): boolean {
  return NATURE_EXPERIENCE_CLOSED_DATES.includes(
    activityDate as (typeof NATURE_EXPERIENCE_CLOSED_DATES)[number]
  );
}


// =========================================
// ตรวจว่าวันที่สามารถจัดกิจกรรมได้หรือไม่
// =========================================

export function isNatureExperienceAvailable(
  activityDate: string
): boolean {
  // ไม่มีวันที่
  if (!activityDate) {
    return false;
  }

  // ก่อนวันเปิดกิจกรรม
  if (
    activityDate <
    NATURE_EXPERIENCE.startDate
  ) {
    return false;
  }

  // หลังวันปิดกิจกรรม
  if (
    activityDate >
    NATURE_EXPERIENCE.endDate
  ) {
    return false;
  }

  // เป็นวันที่งดกิจกรรม
  if (
    isNatureExperienceClosedDate(
      activityDate
    )
  ) {
    return false;
  }

  return true;
}


// =========================================
// คำนวณราคากิจกรรม
// =========================================
//
// ราคา:
// 899 บาท / คน
//
// คิดเพียงครั้งเดียวต่อการจองกิจกรรม
// ไม่คูณจำนวนคืน
//
// ตัวอย่าง:
// 1 คน = 899
// 2 คน = 1,798
// 3 คน = 2,697
// 4 คน = 3,596
//
// =========================================

export function calculateNatureExperienceTotal(
  activityDate: string,
  participants: number,
  selected: boolean
): number {
  // ลูกค้าไม่ได้เลือกกิจกรรม
  if (!selected) {
    return 0;
  }

  // วันที่ไม่สามารถจัดกิจกรรม
  if (
    !isNatureExperienceAvailable(
      activityDate
    )
  ) {
    return 0;
  }

  // ไม่มีผู้เข้าร่วม
  if (participants <= 0) {
    return 0;
  }

  return (
    participants *
    NATURE_EXPERIENCE.pricePerPerson
  );
}