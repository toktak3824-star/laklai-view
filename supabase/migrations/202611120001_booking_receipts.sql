-- Laklai View: receipt records + private PDF storage bucket
-- Keeps the existing confirm_booking_payment RPC unchanged.
-- payment_id / booking_id types are copied from the existing tables to avoid
-- assuming their underlying ID types.

CREATE TABLE IF NOT EXISTS public.booking_receipts AS
SELECT
  p.id AS payment_id,
  b.id AS booking_id
FROM public.payments AS p
CROSS JOIN public.bookings AS b
WHERE FALSE;

ALTER TABLE public.booking_receipts
  ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS receipt_no text,
  ADD COLUMN IF NOT EXISTS receipt_type text NOT NULL DEFAULT 'payment',
  ADD COLUMN IF NOT EXISTS amount_received bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS booking_total bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS cumulative_received bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS remaining_amount bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS pdf_path text,
  ADD COLUMN IF NOT EXISTS email_sent boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS email_sent_at timestamptz,
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

-- Add constraints idempotently.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.booking_receipts'::regclass
      AND conname = 'booking_receipts_pkey'
  ) THEN
    ALTER TABLE public.booking_receipts
      ADD CONSTRAINT booking_receipts_pkey PRIMARY KEY (id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.booking_receipts'::regclass
      AND conname = 'booking_receipts_payment_id_fkey'
  ) THEN
    ALTER TABLE public.booking_receipts
      ADD CONSTRAINT booking_receipts_payment_id_fkey
      FOREIGN KEY (payment_id) REFERENCES public.payments(id) ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.booking_receipts'::regclass
      AND conname = 'booking_receipts_booking_id_fkey'
  ) THEN
    ALTER TABLE public.booking_receipts
      ADD CONSTRAINT booking_receipts_booking_id_fkey
      FOREIGN KEY (booking_id) REFERENCES public.bookings(id) ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.booking_receipts'::regclass
      AND conname = 'booking_receipts_receipt_type_check'
  ) THEN
    ALTER TABLE public.booking_receipts
      ADD CONSTRAINT booking_receipts_receipt_type_check
      CHECK (receipt_type IN ('deposit', 'payment', 'full'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.booking_receipts'::regclass
      AND conname = 'booking_receipts_amounts_nonnegative'
  ) THEN
    ALTER TABLE public.booking_receipts
      ADD CONSTRAINT booking_receipts_amounts_nonnegative
      CHECK (
        amount_received >= 0 AND booking_total >= 0
        AND cumulative_received >= 0 AND remaining_amount >= 0
      );
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS booking_receipts_payment_id_uidx
  ON public.booking_receipts(payment_id);

CREATE UNIQUE INDEX IF NOT EXISTS booking_receipts_receipt_no_uidx
  ON public.booking_receipts(receipt_no)
  WHERE receipt_no IS NOT NULL;

CREATE INDEX IF NOT EXISTS booking_receipts_booking_id_created_at_idx
  ON public.booking_receipts(booking_id, created_at DESC);

ALTER TABLE public.booking_receipts ENABLE ROW LEVEL SECURITY;

